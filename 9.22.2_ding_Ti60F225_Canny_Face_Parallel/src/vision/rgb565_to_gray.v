//======================================================================
//  rgb565_to_gray.v
//----------------------------------------------------------------------
//  RGB565 -> 8bit 灰度。Canny 链路（高斯 / 中值 / Sobel / NMS）的入口级。
//
//  输入格式与 example_top.v 的 DDR 读回通路严格一致：
//      rgb565_i = { R[4:0], G[5:0], B[4:0] }
//                 R = rgb565_i[15:11]
//                 G = rgb565_i[10:5]
//                 B = rgb565_i[4:0]
//  （对应 example_top.v 里 lcd_data_r/g/b 的取位方式）
//
//  算法：
//      1) 各通道先用 MSB 复制扩展到 8bit（比单纯左移补零更接近满量程，
//         黑=0 / 白=255 两端都能取到）：
//             R8 = {R5, R5[4:2]}
//             G8 = {G6, G6[5:4]}
//             B8 = {B5, B5[4:2]}
//      2) Y = (77*R8 + 150*G8 + 29*B8) >> 8
//         权重和 = 77+150+29 = 256，故结果天然落在 [0,255]，无需饱和处理。
//
//  实现要点：
//      * 全部用移位加法，不用乘法器 / 除法器：
//            77  = 64 + 8 + 4 + 1
//            150 = 128 + 16 + 4 + 2
//            29  = 32 - 2 - 1
//      * 单级流水：1 拍延迟，de / x / y 同步透传，便于链条中任意插入。
//
//  关键取值参考（MSB 复制扩展下）：
//      纯黑 16'h0000 ->   0
//      纯白 16'hFFFF -> 255
//      纯红 16'hF800 ->  76
//      纯绿 16'h07E0 -> 149
//      纯蓝 16'h001F ->  28
//======================================================================
`timescale 1ns/1ps

module rgb565_to_gray #(
	parameter AWIDTH = 11			// 列地址位宽（640 用 10，1280 用 11）
)(
	input  wire					clk,
	input  wire					rst_n,		// 同步复位，低有效

	input  wire					de_i,		// 数据使能
	input  wire [AWIDTH-1:0]	x_i,		// 输入列坐标
	input  wire [9:0]			y_i,		// 输入行坐标
	input  wire [15:0]			rgb565_i,	// {R[4:0], G[5:0], B[4:0]}

	output reg  [7:0]			gray_o,		// 灰度输出（与 de_o 同拍）
	output reg					de_o,
	output reg  [AWIDTH-1:0]	x_o,
	output reg  [9:0]			y_o
);

	//------------------------------------------------------------------
	// 1. 通道拆分 + MSB 复制扩展到 8bit
	//------------------------------------------------------------------
	wire [4:0] r5 = rgb565_i[15:11];
	wire [5:0] g6 = rgb565_i[10:5];
	wire [4:0] b5 = rgb565_i[4:0];

	wire [7:0] r8 = {r5, r5[4:2]};
	wire [7:0] g8 = {g6, g6[5:4]};
	wire [7:0] b8 = {b5, b5[4:2]};

	//------------------------------------------------------------------
	// 2. 加权和（移位加法）
	//------------------------------------------------------------------
	wire [15:0] wr = (r8 << 6) + (r8 << 3) + (r8 << 2) + r8;			// 77 * R8
	wire [15:0] wg = (g8 << 7) + (g8 << 4) + (g8 << 2) + (g8 << 1);		// 150 * G8
	wire [15:0] wb = (b8 << 5) - (b8 << 1) - b8;						// 29 * B8

	wire [15:0] ysum = wr + wg + wb;

	wire [7:0]  y8 = ysum[15:8];		// 权重和 256 -> 右移 8 位

	//------------------------------------------------------------------
	// 3. 单级流水输出
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			gray_o <= 8'd0;
			de_o   <= 1'b0;
			x_o    <= {AWIDTH{1'b0}};
			y_o    <= 10'd0;
		end else begin
			gray_o <= y8;
			de_o   <= de_i;
			x_o    <= x_i;
			y_o    <= y_i;
		end
	end

endmodule
