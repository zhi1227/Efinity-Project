//======================================================================
//  nms3x3.v
//----------------------------------------------------------------------
//  3x3 非极大值抑制（NMS）。Canny 链路的细化级，接在 Sobel 之后。
//
//  作用：沿梯度方向比较，中心像素的幅值若不是局部最大则置 0（抑制），
//        把 Sobel 输出的“粗边缘”细化成候选单像素边缘。
//
//  输入流的打包（关键，与前级约定）：
//      Sobel 每像素输出 {dir[1:0], mag[11:0]}（共 14bit），
//      把 dir 和 mag **打包成一个 14bit 像素** 送第三级 line_buffer_3x3
//      （DWIDTH=14）。这样 dir 随 mag 一起移位，窗口中心处的 dir 与 mag
//      天然对齐，无需单独的对齐延迟线。
//      window_i = 9 x 14bit = 126bit，每个像素 = {dir[1:0], mag[11:0]}，
//      dir 在高 2 位。p00 在最高位。
//
//  窗口像素与位序（与 line_buffer_3x3 一致，p00=左上，p22=右下）：
//      window_i[125:112]=p00  [111:98]=p01  [ 97:84]=p02
//      window_i[ 83:70 ]=p10  [ 69:56]=p11  [ 55:42]=p12
//      window_i[ 41:28 ]=p20  [ 27:14]=p21  [ 13:0 ]=p22
//      中心 = p11。只用中心像素的 dir，邻居的 dir 忽略。
//
//  方向 -> 邻接对（由梯度几何决定，已与 sobel3x3 的 dir 定义对齐）：
//      dir=0 (0°  ,梯度近水平): 比较 左/右    = p10, p12
//      dir=2 (90° ,梯度近竖直): 比较 上/下    = p01, p21
//      dir=1 (45° ,同号主对角): 比较 左上/右下 = p00, p22
//      dir=3 (135°,异号副对角): 比较 右上/左下 = p02, p20
//
//  判决：
//      keep = (m_center >= n1) && (m_center >= n2)
//      nms_mag = keep ? m_center : 0
//      说明：非对称 > / >= 平局只保留平台的一侧，避免双像素边缘；
//            粗出的部分由后续双阈值 + 迟滞清理。这是 FPGA 常用取舍，
//            避免严格 > 在平台上造成边缘断点。
//
//  实现：纯组合 + 1 级输出寄存器，x / y / valid 同步透传 1 拍。
//======================================================================
`timescale 1ns/1ps

module nms3x3 #(
	parameter AWIDTH = 11			// 列地址位宽（640 用 10，1280 用 11）
)(
	input  wire					clk,
	input  wire					rst_n,		// 同步复位，低有效

	input  wire					win_valid_i,
	input  wire [AWIDTH-1:0]	x_i,
	input  wire [9:0]			y_i,
	input  wire [125:0]			window_i,	// 9 x {dir[1:0], mag[11:0]}

	output reg  [11:0]			nms_mag_o,	// 抑制后幅值（非局部最大则为 0）
	output reg					valid_o,
	output reg  [AWIDTH-1:0]	x_o,
	output reg  [9:0]			y_o
);

	//------------------------------------------------------------------
	// 拆窗：取出 9 个像素的幅值，以及中心像素的方向
	// 每个像素 14bit = {dir[1:0], mag[11:0]}，dir 在高 2 位
	//------------------------------------------------------------------
	wire [11:0] m00 = window_i[123:112];
	wire [11:0] m01 = window_i[109:98];
	wire [11:0] m02 = window_i[95:84];
	wire [11:0] m10 = window_i[81:70];
	wire [11:0] m11 = window_i[67:56];	// 中心幅值
	wire [11:0] m12 = window_i[53:42];
	wire [11:0] m20 = window_i[39:28];
	wire [11:0] m21 = window_i[25:14];
	wire [11:0] m22 = window_i[11:0];

	wire [1:0]  dc  = window_i[69:68];	// 中心像素方向（p11 的 dir）

	//------------------------------------------------------------------
	// 按中心方向选两个沿梯度的邻居
	//------------------------------------------------------------------
	reg [11:0] n1, n2;
	always @(*) begin
		case (dc)
			2'd0:	 begin n1 = m10; n2 = m12; end	// 0°  : 左 / 右
			2'd2:	 begin n1 = m01; n2 = m21; end	// 90° : 上 / 下
			2'd1:	 begin n1 = m00; n2 = m22; end	// 45° : 左上 / 右下
			default: begin n1 = m02; n2 = m20; end	// 135°: 右上 / 左下
		endcase
	end

	//------------------------------------------------------------------
	// 非极大值抑制
	//------------------------------------------------------------------
	wire        keep    = (m11 > n1) && (m11 >= n2);
	wire [11:0] nms_mag = keep ? m11 : 12'd0;

	//------------------------------------------------------------------
	// 输出寄存（1 拍流水）
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			nms_mag_o <= 12'd0;
			valid_o   <= 1'b0;
			x_o       <= {AWIDTH{1'b0}};
			y_o       <= 10'd0;
		end else begin
			nms_mag_o <= nms_mag;
			valid_o   <= win_valid_i;
			x_o       <= x_i;
			y_o       <= y_i;
		end
	end

endmodule
