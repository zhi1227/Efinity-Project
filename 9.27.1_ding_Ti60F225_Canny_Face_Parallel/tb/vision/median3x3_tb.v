//======================================================================
//  median3x3_tb.v   —— 自检测试台
//----------------------------------------------------------------------
//  验证目标：
//    [A] median-of-9 选择网络 与 真排序取中值 完全一致
//    [B] x / y / valid 透传对齐（1 拍延迟）
//    [C] 对椒盐 / 脉冲噪声的鲁棒性（定向用例）
//
//  参考模型用「冒泡排序后取中间元素」，与 DUT 的「选择网络」是两条
//  不同的实现路径，才能真正校验算法正确性，而不是自我循环验证。
//
//  覆盖：约 20 组定向用例（全 0 / 全 255 / 单调 / 椒盐 / 边界 / 重复值）
//        + 100000 组随机窗口。
//  说明：中值与像素位置无关，因此本测试台不关心 p00..p22 的打包顺序，
//        只喂 9 个值的集合比对中值即可。
//======================================================================
`timescale 1ns/1ns

module median3x3_tb;

	reg 				clk = 0;
	reg 				rst_n = 0;
	reg 				win_valid = 0;
	reg  [10:0]			xin = 0;
	reg  [9:0]			yin = 0;
	reg  [71:0]			win = 0;

	wire [7:0]			med;
	wire				med_valid;
	wire [10:0]			xout;
	wire [9:0]			yout;

	median3x3 #(.AWIDTH(11)) u_dut (
		.clk			(clk),
		.rst_n			(rst_n),
		.win_valid_i	(win_valid),
		.x_i			(xin),
		.y_i			(yin),
		.window_i		(win),
		.med_o			(med),
		.med_valid_o	(med_valid),
		.x_o			(xout),
		.y_o			(yout)
	);

	always #5 clk = ~clk;

	//------------------------------------------------------------------
	// 参考模型：排序取中间（独立路径）
	//------------------------------------------------------------------
	function [7:0] ref_med;
		input [71:0] w;
		reg [7:0] a [0:8];
		reg [7:0] t;
		integer i, j;
		begin
			a[0]=w[71:64]; a[1]=w[63:56]; a[2]=w[55:48];
			a[3]=w[47:40]; a[4]=w[39:32]; a[5]=w[31:24];
			a[6]=w[23:16]; a[7]=w[15:8];  a[8]=w[7:0];
			for (i = 0; i < 9; i = i + 1)
				for (j = i + 1; j < 9; j = j + 1)
					if (a[j] < a[i]) begin t = a[i]; a[i] = a[j]; a[j] = t; end
			ref_med = a[4];
		end
	endfunction

	//------------------------------------------------------------------
	// 打包 9 个值为一个窗口
	//------------------------------------------------------------------
	function [71:0] pack9;
		input [7:0] v0,v1,v2,v3,v4,v5,v6,v7,v8;
		begin
			pack9 = {v0,v1,v2,v3,v4,v5,v6,v7,v8};
		end
	endfunction

	integer err_cnt = 0;
	integer ok_cnt  = 0;
	integer k;
	reg [71:0] w;
	reg [10:0] tagx = 0;
	reg [9:0]  tagy = 0;

	//------------------------------------------------------------------
	// 施加一个窗口并校验（DUT 1 拍延迟）
	//------------------------------------------------------------------
	task apply;
		input [71:0] wv;
		reg [7:0] exp;
		begin
			exp  = ref_med(wv);
			tagx = tagx + 1;
			if (tagx == 1280) begin tagx = 0; tagy = tagy + 1; end
			@(negedge clk);
			win = wv; win_valid = 1; xin = tagx; yin = tagy;
			@(negedge clk);
			win_valid = 0;
			if ((med_valid !== 1'b1) || (med !== exp) || (xout !== tagx) || (yout !== tagy)) begin
				err_cnt = err_cnt + 1;
				if (err_cnt <= 6)
					$display("  [FAIL] win=%h  dut=%0d ref=%0d  xout=%0d/%0d yout=%0d/%0d",
					         wv, med, exp, xout, tagx, yout, tagy);
			end else begin
				ok_cnt = ok_cnt + 1;
			end
		end
	endtask

	//------------------------------------------------------------------
	// 主流程
	//------------------------------------------------------------------
	initial begin
		repeat (4) @(negedge clk);
		rst_n = 1;
		@(negedge clk);

		$display("");
		$display("================ median3x3 自检 ================");

		//--------------------------------------------------------------
		// 定向用例
		//--------------------------------------------------------------
		apply(pack9(  0,  0,  0,  0,  0,  0,  0,  0,  0));	// 全 0
		apply(pack9(255,255,255,255,255,255,255,255,255));	// 全 255
		apply(pack9(  1,  2,  3,  4,  5,  6,  7,  8,  9));	// 单调升 -> 5
		apply(pack9(  9,  8,  7,  6,  5,  4,  3,  2,  1));	// 单调降 -> 5
		// 椒盐噪声：8 黑 1 白 -> 0
		apply(pack9(  0,  0,  0,  0,  0,  0,  0,  0,255));
		apply(pack9(255,  0,  0,  0,  0,  0,  0,  0,  0));
		// 椒盐噪声：8 白 1 黑 -> 255
		apply(pack9(255,255,255,255,255,255,255,255,  0));
		apply(pack9(  0,255,255,255,255,255,255,255,255));
		// 椒盐噪声：4 黑 5 白 -> 255（跨过中点）
		apply(pack9(  0,  0,  0,  0,255,255,255,255,255));
		// 椒盐噪声：5 黑 4 白 -> 0
		apply(pack9(  0,  0,  0,  0,  0,255,255,255,255));
		// 单个离群点（亮斑），其余平坦
		apply(pack9(100,100,100,100,255,100,100,100,100));	// -> 100
		apply(pack9(100,100,100,100,  0,100,100,100,100));	// -> 100
		// 重复值 + 边界
		apply(pack9(  5,  5,  5,  1,  1,  9,  2,  8,  3));	// -> 5
		apply(pack9(  0,  0,  0,  0,255,  0,  0,  0,  0));	// -> 0
		apply(pack9(255,255,255,255,  0,255,255,255,255));	// -> 255
		// 斜坡（模拟边缘），中值应落在中间值
		apply(pack9( 10, 20, 30, 40, 50, 60, 70, 80, 90));	// -> 50
		// 双峰
		apply(pack9( 10, 10, 10, 10,200,200,200,200,200));	// -> 200

		//--------------------------------------------------------------
		// 随机窗口
		//--------------------------------------------------------------
		for (k = 0; k < 100000; k = k + 1) begin
			w = {$random, $random, $random};
			apply(w);
		end

		$display(" 定向 + 随机用例总数 : %0d", ok_cnt + err_cnt);
		$display(" 通过               : %0d", ok_cnt);
		$display(" 错误               : %0d", err_cnt);
		$display("");
		if (err_cnt == 0)
			$display(" >>> ALL TESTS PASS");
		else
			$display(" >>> TEST FAILED  (err=%0d)", err_cnt);
		$display("=================================================");
		$display("");

		$finish;
	end

endmodule
