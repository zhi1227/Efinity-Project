//======================================================================
//  rgb565_to_rgb888_tb.v   —— 自检测试台
//----------------------------------------------------------------------
//  验证目标（三条，全部必须在同一次仿真里成立）：
//    [A] 本模块的 MSB 复制扩展，与独立参考模型逐位一致（穷举 65536 码字）
//    [B] 三个通道各自单调严格递增，且两端 0 -> 0、满量程 -> 255
//    [C] 量化工程当前写法（example_top.v:969-971 的左移补零）相对
//        正确写法的偏差，给出实测数字而不是估算
//
//  参考模型特意用「整数乘法 + 移位」表达，而不是位拼接：
//      R8 = R5*8 + (R5>>2)   G8 = G6*4 + (G6>>4)   B8 = B5*8 + (B5>>2)
//  这样与 DUT 的「位拼接」是两条不同的表达路径，
//  才能真正校验位切片下标有没有写错，而不是自我循环验证。
//
//  纯组合 DUT，每码字施加 #1 后采样，无需时钟。
//======================================================================
`timescale 1ns/1ns

module rgb565_to_rgb888_tb;

	reg  [15:0] code;
	wire [23:0] dut;

	rgb565_to_rgb888 u_dut (
		.rgb565_i (code),
		.rgb888_o (dut)
	);

	integer i;

	//------------------------------------------------------------------
	// 统计量
	//------------------------------------------------------------------
	integer err_cnt;		// DUT 与参考模型不符的码字数
	integer diff_cnt;		// 新写法与旧写法结果不同的码字数
	integer dev_sum;		// 旧写法三通道偏差总和（仅统计不同的码字）
	integer ch_max;			// 旧写法最大单通道偏差
	integer mono_err;		// 单调性 / 端点违规计数

	integer dv_this, dv_r, dv_g, dv_b;

	//------------------------------------------------------------------
	// 参考模型 / 旧写法
	//------------------------------------------------------------------
	reg [7:0] ref_r, ref_g, ref_b;
	reg [23:0] ref888;

	reg [7:0] leg_r, leg_g, leg_b;
	reg [23:0] leg888;

	reg [6:0] vc;			// 通道扫描变量（5bit / 6bit 共用，留够位宽避免自增截断）
	reg [7:0] prev8, cur8;

	//------------------------------------------------------------------
	// 打印单个码字的新旧对照
	//------------------------------------------------------------------
	task show_code;
		input [15:0] c;
		reg [7:0] nr, ng, nb;
		reg [7:0] orr, org, orb;
		begin
			nr  = c[15:11]*8 + (c[15:11]>>2);
			ng  = c[10:5]*4  + (c[10:5]>>4);
			nb  = c[4:0]*8   + (c[4:0]>>2);
			orr = {c[15:11], 3'b0};
			org = {c[10:5],  2'b0};
			orb = {c[4:0],   3'b0};
			$display("   %04h :  新 (%0d,%0d,%0d)   旧 (%0d,%0d,%0d)",
			         c, nr, ng, nb, orr, org, orb);
		end
	endtask

	//------------------------------------------------------------------
	// 主流程
	//------------------------------------------------------------------
	initial begin
		err_cnt  = 0;
		diff_cnt = 0;
		dev_sum  = 0;
		ch_max   = 0;
		mono_err = 0;

		$display("");
		$display("============ rgb565_to_rgb888 穷举自检 ============");

		//--------------------------------------------------------------
		// [A] + [C] 穷举全部 65536 个 RGB565 码字
		//--------------------------------------------------------------
		for (i = 0; i < 65536; i = i + 1) begin
			code = i;
			#1;

			// 独立参考模型（整数乘法 + 移位）
			ref_r = code[15:11]*8 + (code[15:11]>>2);
			ref_g = code[10:5]*4  + (code[10:5]>>4);
			ref_b = code[4:0]*8   + (code[4:0]>>2);
			ref888 = {ref_r, ref_g, ref_b};

			// 工程当前写法：左移补零
			leg_r = {code[15:11], 3'b0};
			leg_g = {code[10:5],  2'b0};
			leg_b = {code[4:0],   3'b0};
			leg888 = {leg_r, leg_g, leg_b};

			if (dut !== ref888) begin
				err_cnt = err_cnt + 1;
				if (err_cnt <= 5)
					$display("   [FAIL] code=%04h  dut=%06h  ref=%06h",
					         code, dut, ref888);
			end

			if (leg888 !== ref888) begin
				diff_cnt = diff_cnt + 1;

				dv_r = (ref_r > leg_r) ? (ref_r - leg_r) : (leg_r - ref_r);
				dv_g = (ref_g > leg_g) ? (ref_g - leg_g) : (leg_g - ref_g);
				dv_b = (ref_b > leg_b) ? (ref_b - leg_b) : (leg_b - ref_b);

				if (dv_r > ch_max) ch_max = dv_r;
				if (dv_g > ch_max) ch_max = dv_g;
				if (dv_b > ch_max) ch_max = dv_b;

				dv_this  = dv_r + dv_g + dv_b;
				dev_sum  = dev_sum + dv_this;
			end
		end

		$display(" [A] DUT 与独立参考模型比对");
		$display("     穷举码字数     : 65536");
		$display("     不一致码字数   : %0d", err_cnt);
		$display("");

		//--------------------------------------------------------------
		// [B] 单个通道单调性 + 端点可及性
		//     直接读 DUT 输出，逐级扫描通道值
		//--------------------------------------------------------------
		// R 通道（5bit）：code = {R5, G6=0, B5=0}  —— 拼接必须恰好 16 位
		prev8 = 8'd0;
		for (vc = 0; vc < 32; vc = vc + 1) begin
			code = {vc[4:0], 6'b0, 5'b0};
			#1;
			cur8 = dut[23:16];
			if ((vc > 0) && (cur8 <= prev8)) mono_err = mono_err + 1;
			prev8 = cur8;
		end
		if (prev8 !== 8'hFF) mono_err = mono_err + 1;

		// G 通道（6bit）：code = {R5=0, G6, B5=0}
		prev8 = 8'd0;
		for (vc = 0; vc < 64; vc = vc + 1) begin
			code = {5'b0, vc[5:0], 5'b0};
			#1;
			cur8 = dut[15:8];
			if ((vc > 0) && (cur8 <= prev8)) mono_err = mono_err + 1;
			prev8 = cur8;
		end
		if (prev8 !== 8'hFF) mono_err = mono_err + 1;

		// B 通道（5bit）：code = {R5=0, G6=0, B5}
		prev8 = 8'd0;
		for (vc = 0; vc < 32; vc = vc + 1) begin
			code = {5'b0, 6'b0, vc[4:0]};
			#1;
			cur8 = dut[7:0];
			if ((vc > 0) && (cur8 <= prev8)) mono_err = mono_err + 1;
			prev8 = cur8;
		end
		if (prev8 !== 8'hFF) mono_err = mono_err + 1;

		$display(" [B] 通道单调性 / 端点可及性");
		$display("     违规数量       : %0d  (R5: 0->0 且 31->255 ; G6: 0->0 且 63->255 ; B5 同 R5)",
		         mono_err);
		$display("");

		//--------------------------------------------------------------
		// 端点取值
		//--------------------------------------------------------------
		$display(" [C] 关键码字对照（新 = MSB 复制，旧 = 左移补零）");
		show_code(16'h0000);
		show_code(16'hFFFF);
		show_code(16'hF800);
		show_code(16'h07E0);
		show_code(16'h001F);
		$display("");

		//--------------------------------------------------------------
		// 旧写法偏差统计
		//--------------------------------------------------------------
		$display(" [D] 旧写法（example_top.v:969-971）偏差量化");
		$display("     结果不同的码字数 : %0d / 65536  (%0d.%02d%%)",
		         diff_cnt,
		         (diff_cnt * 10000 / 65536) / 100,
		         (diff_cnt * 10000 / 65536) % 100);
		$display("     最大单通道偏差   : %0d 级", ch_max);
		$display("     平均单通道偏差   : %0d.%02d 级  (按全部 65536 码字 x 3 通道计)",
		         (dev_sum * 100 / (65536 * 3)) / 100,
		         (dev_sum * 100 / (65536 * 3)) % 100);
		$display("");

		//--------------------------------------------------------------
		// 判定
		//--------------------------------------------------------------
		if ((err_cnt == 0) && (mono_err == 0))
			$display(" >>> ALL TESTS PASS");
		else
			$display(" >>> TEST FAILED  (err=%0d mono=%0d)", err_cnt, mono_err);
		$display("=================================================");
		$display("");

		$finish;
	end

endmodule
