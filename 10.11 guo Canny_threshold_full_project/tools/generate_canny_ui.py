"""Generate the small Chinese/decimal threshold-panel ROM (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

P=Path(__file__).resolve().parents[1]
LINES=[
    'Canny 阈值调节',
    '低阈值:0000 高阈值:0000',
    '短按 K1 减小 / K2 增大',
    '长按 K2 切换高 / 低阈值',
    '长按 K1 两秒退出并保留',
    '长按 K1 两秒进入阈值调节',
]
chars=' '+''.join(sorted(set(''.join(LINES)+'0123456789')-{' '}))
font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',14)
depth=1
while depth<len(chars)*16:depth*=2
words=[0]*depth
for index,ch in enumerate(chars):
    im=Image.new('L',(16,16));d=ImageDraw.Draw(im)
    box=d.textbbox((0,0),ch,font=font)
    d.text(((16-box[2]+box[0])//2-box[0],(16-box[3]+box[1])//2-box[1]),ch,font=font,fill=255)
    for row in range(16):
        words[index*16+row]=sum(1<<(15-x) for x in range(16) if im.getpixel((x,row))>=100)
(P/'canny_ui_font.hex').write_text('\n'.join(f'{v:04x}' for v in words)+'\n')
code=['// Generated by tools/generate_canny_ui.py; digits come from live thresholds.',
      'module canny_ui_glyph_rom(input clk,input[2:0]line_id,input[4:0]char_index,input[3:0]row,',
      ' input[15:0]low_bcd,high_bcd,output reg[15:0]bits);',
      'reg[7:0]glyph;always @*begin glyph=0;case({line_id,char_index})']
for li,line in enumerate(LINES):
    assert len(line)<=22
    for ci,ch in enumerate(line):
        if li==1 and (4<=ci<=7 or 13<=ci<=16):
            src='low_bcd' if ci<=7 else 'high_bcd'
            nibble=7-ci if ci<=7 else 16-ci
            code.append(f"8'd{li*32+ci}:glyph=8'd{chars.index('0')}+{src}[{nibble*4}+:4];")
        elif ch!=' ':
            code.append(f"8'd{li*32+ci}:glyph=8'd{chars.index(ch)};")
code+=['default:glyph=0;endcase end',f'reg[15:0]mem[0:{depth-1}];',
       'initial $readmemh("canny_ui_font.hex",mem);',
       'always @(posedge clk)bits<=mem[{glyph,row}];','endmodule']
(P/'rtl/canny_ui_glyph_rom.v').write_text('\n'.join(code)+'\n')
print(f'Canny UI: {len(chars)} glyphs, {depth*16} ROM bits')
