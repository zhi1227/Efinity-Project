//======================================================================
//  hysteresis_local.v
//----------------------------------------------------------------------
//  Canny 迟滞连接（局部单遍实现）。Canny 链路最后一级窗口化操作，
//  接在双阈值 canny_threshold 之后，输出最终二值边缘图。
//
//  判决规则（标准 Canny 迟滞）：
//      中心 = 强边(cls=2)              -> 一定是边缘
//      中心 = 弱边(cls=1) 且 8 邻居中
//        至少一个是强边                -> 是边缘（被强边“拉”进来）
//      其余                            -> 非边
//
//  与经典算法的关系（诚实说明）：
//      经典 Canny 的迟滞是**迭代传播**的——弱边被强边激活后，它自己
//      也成为“已确认边缘”，可以继续激活更远的弱边，形成长链。
//      本模块是 FPGA 常用的**单遍 3x3 近似**：弱边只被直接的强边
//      邻居激活。差异体现在“弱-弱-强”这类长链的远端会断掉一节。
//      实际上游有 NMS + 双阈值把关，单遍近似的边缘质量在多数场景
//      已足够；若后续实拍发现断边严重，可再迭代一级（把输出回灌
//      再过一个 3x3，或用更大的确认窗口）。
//
//  输入流打包（关键，与前级约定）：
//      双阈值输出的 2bit 分类 cls 当作“像素”送第 4 级
//      line_buffer_3x3（DWIDTH=2），窗口 9 x 2 = 18bit。
//      window_i[17:16]=p00 ... [9:8]=p11(中心) ... [1:0]=p22，
//      p00 在最高位（与 line_buffer_3x3 一致）。
//
//  编码约定（与 canny_threshold 一致）：0=非边 1=弱边 2=强边（3 预留，
//  若出现按非边处理）。
//
//  实现：纯组合 + 1 级输出寄存器，x / y / valid 同步透传 1 拍。
//======================================================================
`timescale 1ns/1ps

module hysteresis_local #(
	parameter AWIDTH = 11			// 列地址位宽（640 用 10，1280 用 11）
)(
	input  wire					clk,
	input  wire					rst_n,		// 同步复位，低有效

	input  wire					win_valid_i,
	input  wire [AWIDTH-1:0]	x_i,
	input  wire [9:0]			y_i,
	input  wire [17:0]			window_i,	// 9 x cls[1:0]，p00 在最高位

	output reg					edge_o,		// 最终二值边缘：1=边缘
	output reg					valid_o,
	output reg  [AWIDTH-1:0]	x_o,
	output reg  [9:0]			y_o
);

	//------------------------------------------------------------------
	// 拆窗：9 个 2bit 分类，p00=左上（最高位），p11=中心，p22=右下
	//------------------------------------------------------------------
	wire [1:0] c00 = window_i[17:16];
	wire [1:0] c01 = window_i[15:14];
	wire [1:0] c02 = window_i[13:12];
	wire [1:0] c10 = window_i[11:10];
	wire [1:0] c11 = window_i[ 9: 8];	// 中心
	wire [1:0] c12 = window_i[ 7: 6];
	wire [1:0] c20 = window_i[ 5: 4];
	wire [1:0] c21 = window_i[ 3: 2];
	wire [1:0] c22 = window_i[ 1: 0];

	//------------------------------------------------------------------
	// 8 邻居中存在强边？
	//------------------------------------------------------------------
	wire nbr_strong = (c00 == 2'd2) | (c01 == 2'd2) | (c02 == 2'd2)
	                | (c10 == 2'd2)                   | (c12 == 2'd2)
	                | (c20 == 2'd2) | (c21 == 2'd2) | (c22 == 2'd2);

	//------------------------------------------------------------------
	// 迟滞判决
	//------------------------------------------------------------------
	wire edge_d = (c11 == 2'd2)					// 强边：直接保留
	            | ((c11 == 2'd1) & nbr_strong);	// 弱边：与强边相邻才保留

	//------------------------------------------------------------------
	// 输出寄存（1 拍流水）
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			edge_o  <= 1'b0;
			valid_o <= 1'b0;
			x_o     <= {AWIDTH{1'b0}};
			y_o     <= 10'd0;
		end else begin
			edge_o  <= edge_d;
			valid_o <= win_valid_i;
			x_o     <= x_i;
			y_o     <= y_i;
		end
	end

endmodule
