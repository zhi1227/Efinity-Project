"""Losslessly recode the existing shared font; never rerasterize its pixels.

The low row-dictionary ID bits use true-dual-port block ROM. Sparse high bits
and the row dictionary use combinational decode. Both clocks retain the same
one-edge address-to-pixel latency as the original uncompressed shared ROM.
"""
from argparse import ArgumentParser
from collections import Counter
from hashlib import sha256
from pathlib import Path
import json

P = Path(__file__).resolve().parents[1]


def make_function(name, width, output_width, entries, default=0):
    lines = [f'function [{output_width-1}:0] {name};',
             f' input [{width-1}:0] address;', ' begin',
             f'  {name}={output_width}\'d{default};', '  case(address)']
    lines.extend(f"   {width}'d{address}: {name}={output_width}'h{value:x};"
                 for address, value in entries if value != default)
    lines.extend(['   default: ;', '  endcase', ' end', 'endfunction'])
    return lines


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--index-bits', type=int, choices=(5, 10), default=10)
    args = parser.parse_args()
    words = [int(x, 16) for x in (P/'shared_font.hex').read_text().split()]
    assert len(words) <= 8192 and all(0 <= x < 65536 for x in words)
    original_words = list(words)
    words += [0] * (8192-len(words))
    counts = Counter(words)
    # Frequent rows receive IDs with no high bits. The zero row is ID zero,
    # which also makes out-of-range original banks retain their zero output.
    dictionary = [0] + sorted((x for x in counts if x),
                              key=lambda x: x)
    ids_by_word = {value: i for i, value in enumerate(dictionary)}
    ids = [ids_by_word[x] for x in words]
    id_width = max(1, (len(dictionary)-1).bit_length())
    low_width = args.index_bits
    high_width = id_width-low_width
    assert high_width > 0
    # Width 10 maps 1024 deep; width 5 maps 2048 deep in a 10-Kbit RAM.
    depth = 1024 if low_width == 10 else 2048
    addr_low_bits = depth.bit_length()-1
    bank_count = (len(original_words)+depth-1)//depth
    bank_width = max(1, (bank_count-1).bit_length())
    mem_addr_bits = 13-addr_low_bits
    mask = (1 << low_width)-1
    for bank in range(bank_count):
        values = ids[bank*depth:(bank+1)*depth]
        (P/f'shared_font_index_bank{bank}.hex').write_text(
            ''.join(f'{x & mask:0{(low_width+3)//4}x}\n' for x in values),
            encoding='ascii')
    code = [
        '// Lossless row-dictionary encoding; generated by compress_shared_font_ram.py.',
        '// Original shared_font.hex and shared_font_bank*.hex remain the pixel reference.',
        '// Read latency stays one edge independently in the HDMI and LVDS domains.',
        'module shared_glyph_rom(input clk_hdmi,input[12:0]addr_hdmi,output reg[15:0]bits_hdmi,',
        ' input clk_lvds,input[12:0]addr_lvds,output reg[15:0]bits_lvds);',
        f'reg[{mem_addr_bits-1}:0] hbank,lbank;',
        f'reg[{high_width-1}:0] hhigh,lhigh;',
        f'reg[{low_width-1}:0] hlow,llow;']
    code += make_function('row_high', 13, high_width,
                          ((i, value >> low_width) for i, value in enumerate(ids)))
    code += make_function('decode_row', id_width, 16, enumerate(dictionary))
    code += [
        'always @(posedge clk_hdmi) begin',
        f' hbank<=addr_hdmi[12:{addr_low_bits}]; hhigh<=row_high(addr_hdmi);',
        'end',
        'always @(posedge clk_lvds) begin',
        f' lbank<=addr_lvds[12:{addr_low_bits}]; lhigh<=row_high(addr_lvds);',
        'end']
    for bank in range(bank_count):
        code += [
            f'(* ram_style="block" *) reg[{low_width-1}:0] bank{bank}[0:{depth-1}];',
            f'reg[{low_width-1}:0] h{bank},l{bank};',
            f'initial $readmemh("shared_font_index_bank{bank}.hex",bank{bank});',
            f'always @(posedge clk_hdmi) h{bank}<=bank{bank}[addr_hdmi[{addr_low_bits-1}:0]];',
            f'always @(posedge clk_lvds) l{bank}<=bank{bank}[addr_lvds[{addr_low_bits-1}:0]];']
    for port, select, prefix, high, low in [('hdmi','hbank','h','hhigh','hlow'),
                                           ('lvds','lbank','l','lhigh','llow')]:
        code += ['always @* begin', f' {low}=0;', f' case({select})']
        code += [f"  {mem_addr_bits}'d{bank}: {low}={prefix}{bank};"
                 for bank in range(bank_count)]
        code += ['  default: ;', ' endcase',
                 f' bits_{port}=decode_row({{{high},{low}}});', 'end']
    code += ['endmodule']
    (P/'rtl/shared_glyph_rom.v').write_text('\n'.join(code)+'\n', encoding='ascii')
    for i, value in enumerate(words):
        index = ids[i]
        assert dictionary[index] == value
    report = {
        'original_reference': 'shared_font.hex',
        'original_sha256': sha256((P/'shared_font.hex').read_bytes()).hexdigest(),
        'original_rows': len(original_words), 'valid_address_space': 8192,
        'distinct_rows': len(dictionary), 'index_low_bits': low_width,
        'index_high_bits': high_width, 'index_bank_depth': depth,
        'index_bank_count': bank_count,
        'high_index_nonzero_addresses': sum(bool(x >> low_width) for x in ids),
        'latency_clocks': 1, 'independent_clock_ports': 2,
        'reference_files_modified': False,
        'roundtrip_all_8192_rows': 'PASS',
    }
    output = P/'reports/ram_optimization_20261020'
    output.mkdir(parents=True, exist_ok=True)
    (output/'shared_font_encoding.json').write_text(
        json.dumps(report, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
