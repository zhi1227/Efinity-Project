//======================================================================
//  median3x3.v
//----------------------------------------------------------------------
//  3x3 中值滤波。Canny 链路的预处理级 —— 用中值滤波替代高斯滤波。
//
//  为什么用中值而不是高斯：
//    * 高斯是线性加权平均，会轻微模糊边缘；中值是非线性选取，
//      对传感器的椒盐 / 脉冲噪声更鲁棒，且**不模糊边缘**，更利于后续 Sobel。
//    * 代价：中值需要排序网络，比高斯的移位加法贵 LUT，
//      但 Ti60F225 余量充足（综合报告显示 LUT / BRAM 都很空）。
//    * 与高斯共用同一个 3x3 窗口（line_buffer_3x3），无需改行缓存。
//
//  输入窗口（与 line_buffer_3x3 的 window_o 完全一致的打包）：
//      window_i = {p00..p02, p10..p12, p20..p22}，p00 在最高位（72bit）
//  注意：中值与像素的空间位置无关，只取决于 9 个值的集合，
//        因此即便 p00..p22 的排列与预期不同，中值结果也不受影响。
//
//  算法（median-of-9 选择网络，对 3x3 是精确解，非近似）：
//      1) 每列排序：col_i -> (lo_i, mid_i, hi_i)
//      2) a = max(lo_0, lo_1, lo_2)      （三列最小值中的最大者）
//         b = med(mid_0, mid_1, mid_2)    （三列中值的中值）
//         c = min(hi_0, hi_1, hi_2)       （三列最大值中的最小者）
//      3) median = med(a, b, c)
//
//  实现：纯组合选择网络 + 1 级输出寄存器（与 rgb565_to_gray 风格一致），
//        x / y / valid 同步透传 1 拍。比较器全部为无符号 8bit 比较 + 选择。
//======================================================================
`timescale 1ns/1ps

module median3x3 #(
	parameter AWIDTH = 11			// 列地址位宽（640 用 10，1280 用 11）
)(
	input  wire					clk,
	input  wire					rst_n,		// 同步复位，低有效

	input  wire					win_valid_i,
	input  wire [AWIDTH-1:0]	x_i,
	input  wire [9:0]			y_i,
	input  wire [71:0]			window_i,	// {p00..p02, p10..p12, p20..p22}

	output reg  [7:0]			med_o,		// 中值输出（与 med_valid_o 同拍）
	output reg					med_valid_o,
	output reg  [AWIDTH-1:0]	x_o,
	output reg  [9:0]			y_o
);

	//------------------------------------------------------------------
	// 拆窗（位置对中值无影响，仅为可读性）
	//------------------------------------------------------------------
	wire [7:0] p00 = window_i[71:64];
	wire [7:0] p01 = window_i[63:56];
	wire [7:0] p02 = window_i[55:48];
	wire [7:0] p10 = window_i[47:40];
	wire [7:0] p11 = window_i[39:32];
	wire [7:0] p12 = window_i[31:24];
	wire [7:0] p20 = window_i[23:16];
	wire [7:0] p21 = window_i[15:8];
	wire [7:0] p22 = window_i[7:0];

	//------------------------------------------------------------------
	// 基本比较器（无符号 8bit）
	//------------------------------------------------------------------
	function [7:0] min3;
		input [7:0] a, b, c;
		reg   [7:0] m;
		begin
			m    = (a < b) ? a : b;
			min3 = (m < c) ? m : c;
		end
	endfunction

	function [7:0] max3;
		input [7:0] a, b, c;
		reg   [7:0] m;
		begin
			m    = (a > b) ? a : b;
			max3 = (m > c) ? m : c;
		end
	endfunction

	function [7:0] med3;
		input [7:0] a, b, c;
		reg   [7:0] hi, lo, mid;
		begin
			hi   = (a > b) ? a : b;
			lo   = (a > b) ? b : a;
			mid  = (hi > c) ? c : hi;	// min(hi, c)
			med3 = (lo > mid) ? lo : mid;	// max(lo, mid)
		end
	endfunction

	//------------------------------------------------------------------
	// 1) 每列排序：col0=(p00,p10,p20) col1=(p01,p11,p21) col2=(p02,p12,p22)
	//------------------------------------------------------------------
	wire [7:0] lo0 = min3(p00,p10,p20), mid0 = med3(p00,p10,p20), hi0 = max3(p00,p10,p20);
	wire [7:0] lo1 = min3(p01,p11,p21), mid1 = med3(p01,p11,p21), hi1 = max3(p01,p11,p21);
	wire [7:0] lo2 = min3(p02,p12,p22), mid2 = med3(p02,p12,p22), hi2 = max3(p02,p12,p22);

	//------------------------------------------------------------------
	// 2) 三个候选
	//------------------------------------------------------------------
	wire [7:0] cand_a = max3(lo0,  lo1,  lo2 );	// 三列最小值的最大
	wire [7:0] cand_b = med3(mid0, mid1, mid2);	// 三列中值的中值
	wire [7:0] cand_c = min3(hi0,  hi1,  hi2 );	// 三列最大值的最小

	//------------------------------------------------------------------
	// 3) 最终中值
	//------------------------------------------------------------------
	wire [7:0] median = med3(cand_a, cand_b, cand_c);

	//------------------------------------------------------------------
	// 输出寄存（1 拍流水）
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			med_o       <= 8'd0;
			med_valid_o <= 1'b0;
			x_o         <= {AWIDTH{1'b0}};
			y_o         <= 10'd0;
		end else begin
			med_o       <= median;
			med_valid_o <= win_valid_i;
			x_o         <= x_i;
			y_o         <= y_i;
		end
	end

endmodule
