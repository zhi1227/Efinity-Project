//======================================================================
//  rgb565_to_ycbcr_skin.v
//----------------------------------------------------------------------
//  Task 1：YCbCr 肤色分割（替换 face_reader_720p 的判据）
//
//  为什么换掉 face_reader_720p：
//      原判据只有 U = R - G，且阈值写成 10<U<90，
//      对木色桌面、暖光白墙、黄色物体都会判成肤色，误检率过高。
//      本模块用 BT.601 full-range 的 Y/Cb/Cr 三通道联合判据。
//
//  算法（BT.601 full range，整数近似）：
//      通道扩展（MSB 复制，与 rgb565_to_gray / rgb565_to_rgb888 一致）：
//          R8 = {R5, R5[4:2]}    G8 = {G6, G6[5:4]}    B8 = {B5, B5[4:2]}
//      Y  = ( 77*R + 150*G +  29*B) >> 8
//      Cb = (-43*R -  85*G + 128*B) >> 8 + 128
//      Cr = (128*R - 107*G -  21*B) >> 8 + 128
//
//  系数用移位加法展开（禁 * /）：
//      77  = 64+8+4+1
//     150  = 128+16+4+2
//      29  = 32-2-1
//      43  = 32+8+2+1
//      85  = 64+16+4+1
//     128  = 128
//     107  = 64+32+8+2+1
//      21  = 16+4+1
//
//  判据（三通道同时满足才判肤色）：
//      cb_min <= Cb <= cb_max    默认 77..127
//      cr_min <= Cr <= cr_max    默认 133..173
//      y_min  <= Y  <= y_max     默认 40..235
//
//  为什么三个都要：
//      · 只要 Cb/Cr 会把深红、深棕也收进来（Cr 高但 Y 低）→ 故加 Y 下限
//      · 只要 Cb/Cr 会把纯白（Cb=Cr=128）漏掉？不会，128 落在 77..127 之外
//        （Cb=128 > 127），故白色天然被排除，无需额外处理
//      · Y 上限 235 排除过曝区（可能已失去颜色信息）
//
//  复位语义：本模块无 rst_n 端口吗？—— 不，本模块有 rst_n，
//            与 Canny 链模块风格一致（点进点出 + 1 拍流水）。
//
//  延迟：严格 1 拍（输出寄存器）。
//        与 rgb565_to_gray 同构，方便与 Canny 链做延迟对齐。
//
//  接口与 face_reader_720p 同构（点进点出），便于直接替换：
//      face_reader: image_in_R/G/B, pixel_x[10:0], pixel_y[10:0], pixel_valid
//                   -> binary_output, output_valid
//      本模块     : rgb565_i[15:0], x_i[10:0], y_i[9:0], de_i
//                   -> skin_o, de_o, x_o, y_o
//  差异说明：
//      · 本模块吃 RGB565 原始字，不需要外部先转 RGB888（省 LUT）
//      · y 用 10bit（0..719）而非 face_reader 的 11bit（项目位宽约定）
//      · 本模块透传 x/y，face_reader 不透传 —— 后续 CCL 不依赖 x/y，
//        但 tracker/overlay 对齐需要，故这里透传
//======================================================================
`timescale 1ns/1ps

module rgb565_to_ycbcr_skin #(
	parameter AWIDTH = 11
)(
	input  wire				clk,
	input  wire				rst_n,			// 同步复位，低有效
	input  wire				de_i,			// 数据使能
	input  wire [AWIDTH-1:0]x_i,			// 输入列坐标 0..1279
	input  wire [9:0]		y_i,			// 输入行坐标 0..719
	input  wire [15:0]		rgb565_i,		// {R[4:0], G[5:0], B[4:0]}

	// 运行时可调阈值（默认取计划规定的肤色区间）
	input  wire [7:0]		cb_min_i,		// 默认 77
	input  wire [7:0]		cb_max_i,		// 默认 127
	input  wire [7:0]		cr_min_i,		// 默认 133
	input  wire [7:0]		cr_max_i,		// 默认 173
	input  wire [7:0]		y_min_i,		// 默认 40
	input  wire [7:0]		y_max_i,		// 默认 235

	output reg				skin_o,			// 1 = 肤色
	output reg				de_o,
	output reg  [AWIDTH-1:0]x_o,
	output reg  [9:0]		y_o
);

	//------------------------------------------------------------------
	// 1. 通道拆分 + MSB 复制扩展到 8bit
	//------------------------------------------------------------------
	wire [4:0] r5 = rgb565_i[15:11];
	wire [5:0] g6 = rgb565_i[10:5];
	wire [4:0] b5 = rgb565_i[4:0];

	wire [7:0] r8 = {r5, r5[4:2]};
	wire [7:0] g8 = {g6, g6[5:4]};
	wire [7:0] b8 = {b5, b5[4:2]};

	//------------------------------------------------------------------
	// 1b. ★ 零扩展中间量（关键！）
	//     Verilog-2001 的表达式位宽由**操作数自身**决定，与左侧信号无关。
	//     若直接写 (r8<<7)：r8 是 8bit，左移结果按 8bit 截断，
	//     231<<7 = 29568 被截成 128 —— 这是本项目踩过的真实 bug。
	//     故所有参与移位的量先零扩展到 16bit，再移位。
	//------------------------------------------------------------------
	wire [15:0] r16 = {8'h00, r8};
	wire [15:0] g16 = {8'h00, g8};
	wire [15:0] b16 = {8'h00, b8};

	// 16bit 有符号视图（用于 Cb/Cr 的负数运算）
	wire signed [15:0] rs = {8'h00, r8};
	wire signed [15:0] gs = {8'h00, g8};
	wire signed [15:0] bs = {8'h00, b8};

	//------------------------------------------------------------------
	// 2. Y = (77R + 150G + 29B) >> 8
	//    与 rgb565_to_gray 完全相同的系数，保证两条链的灰度一致
	//    77=64+8+4+1   150=128+16+4+2   29=32-2-1
	//    范围校验：77*255+150*255+29*255 = 65280 < 65536，16bit 够用
	//------------------------------------------------------------------
	wire [15:0] wr = (r16 << 6) + (r16 << 3) + (r16 << 2) + r16;			// 77*R8
	wire [15:0] wg = (g16 << 7) + (g16 << 4) + (g16 << 2) + (g16 << 1);	// 150*G8
	wire [15:0] wb = (b16 << 5) - (b16 << 1) - b16;						// 29*B8
	wire [15:0] ysum = wr + wg + wb;
	wire [7:0]  y8 = ysum[15:8];

	//------------------------------------------------------------------
	// 3. Cb = 128 + ((-43R - 85G + 128B) >> 8)
	//    注意：和可能为负，必须用有符号数，且 >> 是算术右移
	//    43=32+8+2+1   85=64+16+4+1   128=128
	//    范围：|和| <= 43*255+85*255 = 32640，16bit 有符号（±32767）刚好够，
	//          但为安全（含 +128B 后正向最大 128*255=32640）取 17bit
	//------------------------------------------------------------------
	wire signed [16:0] cb_r = -(rs <<< 5) - (rs <<< 3) - (rs <<< 1) - rs;	// -43*R8
	wire signed [16:0] cb_g = -(gs <<< 6) - (gs <<< 4) - (gs <<< 2) - gs;	// -85*G8
	wire signed [16:0] cb_b =  (bs <<< 7);									// +128*B8
	wire signed [16:0] cb_sum = cb_r + cb_g + cb_b;

	// 算术右移 8 位取整数部分，再偏置 128
	wire signed [16:0] cb_sft = cb_sum >>> 8;
	wire signed [8:0]  cb_s9  = cb_sft[8:0] + 9'sd128;						// 9bit 防溢出
	wire [7:0]         cb     = (cb_s9 < 0) ? 8'd0 :
	                            (cb_s9 > 255) ? 8'd255 : cb_s9[7:0];		// 饱和

	//------------------------------------------------------------------
	// 4. Cr = 128 + ((128R - 107G - 21B) >> 8)
	//     107 = 64+32+8+2+1    21 = 16+4+1
	//------------------------------------------------------------------
	wire signed [16:0] cr_r =  (rs <<< 7);									// +128*R8
	wire signed [16:0] cr_g = -(gs <<< 6) - (gs <<< 5) - (gs <<< 3)
	                          - (gs <<< 1) - gs;							// -107*G8
	wire signed [16:0] cr_b = -(bs <<< 4) - (bs <<< 2) - bs;				// -21*B8
	wire signed [16:0] cr_sum = cr_r + cr_g + cr_b;

	wire signed [16:0] cr_sft = cr_sum >>> 8;
	wire signed [8:0]  cr_s9  = cr_sft[8:0] + 9'sd128;
	wire [7:0]         cr     = (cr_s9 < 0) ? 8'd0 :
	                            (cr_s9 > 255) ? 8'd255 : cr_s9[7:0];

	//------------------------------------------------------------------
	// 5. 三通道联合判据
	//    注意：cb/cr 已饱和到 0..255，阈值也都在 0..255，
	//          故直接比 8bit 无符号即可（负数已被饱和成 0，天然不通过下限）
	//------------------------------------------------------------------
	wire y_ok  = (y8 >= y_min_i)  && (y8 <= y_max_i);
	wire cb_ok = (cb >= cb_min_i) && (cb <= cb_max_i);
	wire cr_ok = (cr >= cr_min_i) && (cr <= cr_max_i);

	wire skin_d = y_ok & cb_ok & cr_ok;

	//------------------------------------------------------------------
	// 6. 单级流水输出（1 拍）
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			skin_o <= 1'b0;
			de_o   <= 1'b0;
			x_o    <= {AWIDTH{1'b0}};
			y_o    <= 10'd0;
		end else begin
			skin_o <= skin_d;
			de_o   <= de_i;
			x_o    <= x_i;
			y_o    <= y_i;
		end
	end

endmodule
