//======================================================================
//  rgb565_to_rgb888.v
//----------------------------------------------------------------------
//  RGB565 -> RGB888 通道对齐。HDMI/DVI 输出级的最后一道位宽补齐。
//
//  为什么必须有这一步：
//      DVI/HDMI 物理层是 TMDS，只有 3 条差分 lane
//          Lane2 = R, Lane1 = G, Lane0 = B
//      每条 lane 每像素时钟传 8bit 数据 + 2bit 控制（8b/10b 编码），
//      故每像素固定 24bit，协议上不存在 16bit 模式。
//      rgb2dvi 的 vid_pData 也只有 [23:0] 一种接口
//      （src/hdmi_ip/rgb2dvi.v:22，注释：[7:0]B(0), [15:8]G(1), [23:16]R(2)）。
//      而 DDR 里存的是 16bit/像素的 RGB565，所以必须在此补齐。
//
//  注意：这一步**不提升色深**。真实颜色数仍是 5/6/5 = 65536 色，
//        只是把位摊进 8bit 的容器里，属于位宽对齐，不是画质增强。
//
//  输入 / 输出格式（R 在最高字节，与 rgb2dvi 端口注释一致）：
//      rgb565_i = { R[4:0], G[5:0], B[4:0] }    R=[15:11] G=[10:5] B=[4:0]
//      rgb888_o = { R[7:0], G[7:0], B[7:0] }
//
//  扩展方式：MSB 复制（bit replication），不是左移补零。
//      R8 = {R5, R5[4:2]}    G8 = {G6, G6[5:4]}    B8 = {B5, B5[4:2]}
//  等价整数写法（测试台用它做独立参考）：
//      R8 = R5*8 + (R5>>2)   G8 = G6*4 + (G6>>4)   B8 = B5*8 + (B5>>2)
//
//  为什么不能用左移补零 {R5, 3'b0}：
//      满量程取不满。纯白 16'hFFFF 会变成 (248,252,248) 而非 (255,255,255)，
//      白色亮度只剩约 98%，且 R/B 比 G 低 4 级，高光区略微偏绿。
//      MSB 复制保证 0 -> 0、满量程 -> 255 两端都取到；且 5bit/6bit 全量程
//      单调严格递增，不会出现台阶跳变。
//
//  本模块与 src/vision/rgb565_to_gray.v 采用完全相同的扩展方式，
//  以保证「送 Canny 的灰度」和「屏幕上显示的灰度回显」一致。
//
//  纯组合逻辑，0 拍延迟；若要寄存，由调用方承担
//  （顶层已有 passthrough_rgb 寄存器，可直接接在其前面）。
//======================================================================
`timescale 1ns/1ps

module rgb565_to_rgb888 (
	input  wire [15:0]	rgb565_i,	// {R[4:0], G[5:0], B[4:0]}
	output wire [23:0]	rgb888_o	// {R[7:0], G[7:0], B[7:0]}
);

	//------------------------------------------------------------------
	// 通道拆分
	//------------------------------------------------------------------
	wire [4:0] r5 = rgb565_i[15:11];
	wire [5:0] g6 = rgb565_i[10:5];
	wire [4:0] b5 = rgb565_i[4:0];

	//------------------------------------------------------------------
	// MSB 复制扩展到 8bit
	//------------------------------------------------------------------
	wire [7:0] r8 = {r5, r5[4:2]};
	wire [7:0] g8 = {g6, g6[5:4]};
	wire [7:0] b8 = {b5, b5[4:2]};

	assign rgb888_o = {r8, g8, b8};

endmodule
