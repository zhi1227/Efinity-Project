//======================================================================
//  sobel3x3.v
//----------------------------------------------------------------------
//  3x3 Sobel 梯度。Canny 链路的核心级，接在中值滤波之后。
//
//  链路位置（注意需要两级行缓存）：
//      Gray -> [LB#1] -> 3x3窗(gray) -> median3x3 -> 滤波像素流
//                                                      |
//                                          [LB#2] -> 3x3窗(滤波) -> sobel3x3
//      即 Sobel 作用在**已滤波**的图像上，所以中值之后还要再开一条
//      line_buffer_3x3 重新成窗。本模块接口与 median3x3 完全一致
//      （都是“窗进、点出”），可无缝接在第二级行缓存后面。
//
//  输入窗口（与 line_buffer_3x3 的 window_o 严格一致，已对照源码注释确认）：
//      window_i = {p00..p02, p10..p12, p20..p22}，p00 在最高位 [71:64]
//      p00 = (x_o-1, y_o-1) 左上角    p22 = (x_o+1, y_o+1) 右下角
//      列：左 = {p00,p10,p20}   右 = {p02,p12,p22}
//      行：上 = {p00,p01,p02}   下 = {p20,p21,p22}
//
//  梯度（标准 Sobel）：
//      Gx = (p02 + 2*p12 + p22) - (p00 + 2*p10 + p20)   // 水平梯度（对竖直边敏感）
//      Gy = (p20 + 2*p21 + p22) - (p00 + 2*p01 + p02)   // 竖直梯度（对水平边敏感）
//      各分量范围 [-1020, 1020]
//
//  输出：
//      mag_o = |Gx| + |Gy|          // L1 幅值，范围 [0, 2040]，12bit 全精度
//                                    （NMS 需要全精度比较；显示用的 8bit 缩放留给下游）
//      dir_o = 梯度方向量化（供 NMS 选邻接对）：
//          0 : 0°   梯度近水平（|Gx| >= 2|Gy|）—— 比较 左/右 邻（p10/p12）
//          2 : 90°  梯度近竖直（|Gy| >= 2|Gx|）—— 比较 上/下 邻（p01/p21）
//          1 : 45°  对角，Gx/Gy 同号（主对角线）—— 比较 左上/右下 邻（p00/p22）
//          3 : 135° 对角，Gx/Gy 异号（副对角线）—— 比较 右上/左下 邻（p02/p20）
//      说明：方向边界用 |G| 因子 2（即 26.6°/63.4°）代替精确的 tan(22.5°/67.5°)，
//            只用移位、零乘法器，是 FPGA Canny 的常用近似；如需更准可再细化。
//
//  实现：纯组合梯度 + 1 级输出寄存器（与 median3x3 风格一致），
//        x / y / valid 同步透传 1 拍。乘 2 全部用拼接 {v,1'b0}，避免移位丢高位。
//======================================================================
`timescale 1ns/1ps

module sobel3x3 #(
	parameter AWIDTH = 11			// 列地址位宽（640 用 10，1280 用 11）
)(
	input  wire					clk,
	input  wire					rst_n,		// 同步复位，低有效

	input  wire					win_valid_i,
	input  wire [AWIDTH-1:0]	x_i,
	input  wire [9:0]			y_i,
	input  wire [71:0]			window_i,	// {p00..p02, p10..p12, p20..p22}

	output reg  [11:0]			mag_o,		// |Gx| + |Gy|
	output reg  [1:0]			dir_o,		// 0:0° 1:45° 2:90° 3:135°
	output reg					valid_o,
	output reg  [AWIDTH-1:0]	x_o,
	output reg  [9:0]			y_o
);

	//------------------------------------------------------------------
	// 拆窗（已对照 line_buffer_3x3 源码注释确认位序）
	//------------------------------------------------------------------
	wire [7:0] p00 = window_i[71:64];
	wire [7:0] p01 = window_i[63:56];
	wire [7:0] p02 = window_i[55:48];
	wire [7:0] p10 = window_i[47:40];
	wire [7:0] p11 = window_i[39:32];
	wire [7:0] p12 = window_i[31:24];
	wire [7:0] p20 = window_i[23:16];
	wire [7:0] p21 = window_i[15:8];
	wire [7:0] p22 = window_i[7:0];

	//------------------------------------------------------------------
	// 行 / 列加权和（乘 2 用拼接，避免 8bit 移位丢高位）
	//------------------------------------------------------------------
	wire [9:0] p10x2 = {p10, 1'b0};
	wire [9:0] p12x2 = {p12, 1'b0};
	wire [9:0] p01x2 = {p01, 1'b0};
	wire [9:0] p21x2 = {p21, 1'b0};

	wire [10:0] colL = p00 + p10x2 + p20;	// 左列加权和
	wire [10:0] colR = p02 + p12x2 + p22;	// 右列加权和
	wire [10:0] rowT = p00 + p01x2 + p02;	// 上行加权和
	wire [10:0] rowB = p20 + p21x2 + p22;	// 下行加权和

	//------------------------------------------------------------------
	// 有符号梯度（13bit 有符号，范围 [-1020,1020]，显式零扩展避免符号歧义）
	//------------------------------------------------------------------
	wire signed [12:0] gx = $signed({2'b00, colR}) - $signed({2'b00, colL});
	wire signed [12:0] gy = $signed({2'b00, rowB}) - $signed({2'b00, rowT});

	//------------------------------------------------------------------
	// L1 幅值
	//------------------------------------------------------------------
	wire [11:0] agx = gx[12] ? (-gx) : gx;	// |Gx|
	wire [11:0] agy = gy[12] ? (-gy) : gy;	// |Gy|
	wire [11:0] mag = agx + agy;			// [0, 2040]

	//------------------------------------------------------------------
	// 方向量化（因子 2 边界，同号 / 异号由 gx、gy 符号位判断）
	//------------------------------------------------------------------
	reg [1:0] dir_c;
	always @(*) begin
		if (agx >= {agy[10:0], 1'b0})		dir_c = 2'd0;	// |Gx| >= 2|Gy| -> 0°
		else if (agy >= {agx[10:0], 1'b0})	dir_c = 2'd2;	// |Gy| >= 2|Gx| -> 90°
		else if (gx[12] == gy[12])			dir_c = 2'd1;	// 同号 -> 45°
		else								dir_c = 2'd3;	// 异号 -> 135°
	end

	//------------------------------------------------------------------
	// 输出寄存（1 拍流水）
	//------------------------------------------------------------------
	always @(posedge clk or negedge rst_n) begin
		if (!rst_n) begin
			mag_o   <= 12'd0;
			dir_o   <= 2'd0;
			valid_o <= 1'b0;
			x_o     <= {AWIDTH{1'b0}};
			y_o     <= 10'd0;
		end else begin
			mag_o   <= mag;
			dir_o   <= dir_c;
			valid_o <= win_valid_i;
			x_o     <= x_i;
			y_o     <= y_i;
		end
	end

endmodule
